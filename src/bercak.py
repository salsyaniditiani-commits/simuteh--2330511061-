# BENTUK STRUCTURING ELEMENT

_BENTUK = {
    "elips": cv2.MORPH_ELLIPSE,
    "persegi": cv2.MORPH_RECT,
    "silang": cv2.MORPH_CROSS
}


def _se(p, uk):
    """Membuat structuring element sesuai parameter."""
    return cv2.getStructuringElement(
        _BENTUK[p["se_bentuk"]],
        (uk, uk)
    )

# 1. PEMBERSIHAN MASK BERCAK

def bersihkan(biner, p):
    """
    Opening membuang titik derau dan potongan tipis.
    Closing menutup celah kecil pada objek.
    """

    hasil = biner.copy()

    # TODO 1: Opening
    if p["se_open"] > 0:
        kernel_open = _se(p, p["se_open"])

        hasil = cv2.morphologyEx(
            hasil,
            cv2.MORPH_OPEN,
            kernel_open
        )

    # TODO 2: Closing
    if p["se_close"] > 0:
        kernel_close = _se(p, p["se_close"])

        hasil = cv2.morphologyEx(
            hasil,
            cv2.MORPH_CLOSE,
            kernel_close
        )

    return hasil

# 2. PENGUKURAN DAN PENYARINGAN KOMPONEN

def ukur_dan_saring(biner, p):
    """
    Mengembalikan mask bercak tersaring dan daftar
    ukuran setiap bercak yang memenuhi kriteria.
    """

    # TODO 3: Label komponen terhubung
    jumlah, label, statistik, centroid = (
        cv2.connectedComponentsWithStats(
            biner,
            connectivity=8
        )
    )

    keluar = np.zeros_like(biner)
    daftar = []

    # Komponen 0 merupakan latar belakang,
    # sehingga proses dimulai dari label 1.
    for i in range(1, jumlah):

        # Mengambil luas komponen
        luas = int(
            statistik[i, cv2.CC_STAT_AREA]
        )

        # Mengambil mask komponen
        komponen = np.uint8(label == i) * 255

        # Mencari kontur komponen
        kontur, _ = cv2.findContours(
            komponen,
            cv2.RETR_EXTERNAL,
            cv2.CHAIN_APPROX_SIMPLE
        )

        if len(kontur) == 0:
            continue

        kontur_utama = max(
            kontur,
            key=cv2.contourArea
        )

        # TODO 4: Menghitung keliling
        keliling = cv2.arcLength(
            kontur_utama,
            True
        )

        # Menghitung kebulatan
        if keliling > 0:
            kebulatan = (
                4 * np.pi * luas / (keliling ** 2)
            )
        else:
            kebulatan = 0

        # Menghitung rasio aspek menggunakan minAreaRect
        persegi_panjang = cv2.minAreaRect(
            kontur_utama
        )

        lebar, tinggi = persegi_panjang[1]

        if min(lebar, tinggi) > 0:
            rasio_aspek = (
                max(lebar, tinggi) /
                min(lebar, tinggi)
            )
        else:
            rasio_aspek = float("inf")

        # TODO 5: Penyaringan komponen
        if (
            luas >= p["luas_min"]
            and kebulatan >= p["bulat_min"]
            and rasio_aspek <= p["rasio_maks"]
        ):

            # Memasukkan komponen yang lolos ke mask
            keluar[label == i] = 255

            # Mencatat karakteristik komponen
            daftar.append({
                "label": i,
                "luas_px": luas,
                "keliling_px": round(keliling, 3),
                "kebulatan": round(kebulatan, 4),
                "rasio_aspek": round(rasio_aspek, 4),
                "lebar_px": round(lebar, 3),
                "tinggi_px": round(tinggi, 3),
                "centroid_x": round(
                    float(centroid[i][0]), 2
                ),
                "centroid_y": round(
                    float(centroid[i][1]), 2
                )
            })

    return keluar, daftar