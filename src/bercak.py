"""bercak.py: analisis bercak SIMUTEH (P7)."""

import json
import cv2
import numpy as np
from utils_tepi import mask_daun_awal, bercak_awal

PARAM_BERCAK = {
    "kanal": 2, "k": 4.0,
    "se_bentuk": "elips", "se_open": 5, "se_close": 5,
    "luas_min": 20, "bulat_min": 0.5, "rasio_maks": 1.8,
    "batas_ringan": 0.1, "batas_berat": 2.0,
    "mm_per_px": 0.4375
}

_BENTUK = {
    "elips": cv2.MORPH_ELLIPSE,
    "persegi": cv2.MORPH_RECT,
    "silang": cv2.MORPH_CROSS
}


def _se(p, ukuran):
    return cv2.getStructuringElement(
        _BENTUK[p["se_bentuk"]], (ukuran, ukuran)
    )


# 1. Pembersihan mask bercak
def bersihkan(biner, p):
    hasil = biner.copy()
    if p["se_open"] > 0:
        hasil = cv2.morphologyEx(
            hasil, cv2.MORPH_OPEN, _se(p, p["se_open"])
        )
    if p["se_close"] > 0:
        hasil = cv2.morphologyEx(
            hasil, cv2.MORPH_CLOSE, _se(p, p["se_close"])
        )
    return hasil


# 2. Pengukuran dan penyaringan komponen
def ukur_dan_saring(biner, p):
    jumlah, label, statistik, centroid = cv2.connectedComponentsWithStats(
        (biner > 0).astype(np.uint8), connectivity=8
    )

    keluar = np.zeros_like(biner)
    daftar = []

    for i in range(1, jumlah):
        luas = int(statistik[i, cv2.CC_STAT_AREA])
        komponen = np.uint8(label == i)
        kontur, _ = cv2.findContours(
            komponen, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE
        )
        if not kontur:
            continue

        c = max(kontur, key=cv2.contourArea)
        keliling = cv2.arcLength(c, True)
        kebulatan = 0 if keliling == 0 else 4 * np.pi * luas / keliling**2

        lebar, tinggi = cv2.minAreaRect(c)[1]
        rasio = max(lebar, tinggi) / max(min(lebar, tinggi), 1)

        # Penyaringan luas, kebulatan, dan rasio aspek
        if (luas >= p["luas_min"] and
            kebulatan >= p["bulat_min"] and
            rasio <= p["rasio_maks"]):

            keluar[label == i] = 255
            daftar.append({
                "label": i,
                "luas_px": luas,
                "luas_mm2": round(luas * p["mm_per_px"]**2, 2),
                "keliling_px": round(keliling, 2),
                "kebulatan": round(kebulatan, 4),
                "rasio_aspek": round(rasio, 4),
                "lebar_px": round(lebar, 2),
                "tinggi_px": round(tinggi, 2),
                "centroid_x": round(float(centroid[i][0]), 2),
                "centroid_y": round(float(centroid[i][1]), 2)
            })

    return keluar, daftar


# 3. Analisis luas bercak dan penentuan kelas
def analisis_daun(img_praproses, p=None):
    p = {**PARAM_BERCAK, **(p or {})}

    m_daun = mask_daun_awal(img_praproses)
    biner = bercak_awal(
        img_praproses, m_daun, kanal=p["kanal"], k=p["k"]
    )
    m_bercak, daftar = ukur_dan_saring(bersihkan(biner, p), p)

    # Menghitung persentase luas bercak terhadap luas daun
    luas_daun = np.count_nonzero(m_daun)
    luas_bercak = np.count_nonzero(m_bercak)
    persen = 100 * luas_bercak / luas_daun if luas_daun > 0 else 0.0

    # Menentukan kelas mutu berdasarkan persentase bercak
    if persen >= p["batas_berat"]:
        kelas = "Berat"
    elif persen >= p["batas_ringan"]:
        kelas = "Ringan"
    else:
        kelas = "Sehat"

    return {
        "mask_daun": m_daun,
        "mask_bercak": m_bercak,
        "jumlah_bercak": len(daftar),
        "persen_bercak": round(float(persen), 3),
        "kelas": kelas,
        "bercak": daftar
    }


# 4. Menyimpan parameter analisis
def simpan_param(p=None, path="../hasil/param_bercak.json"):
    with open(path, "w") as f:
        json.dump({**PARAM_BERCAK, **(p or {})}, f, indent=2)